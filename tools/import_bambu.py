#!/usr/bin/env python3
"""Import Bambu Lab printer profiles from a BambuStudio checkout.

Writes profiles/printers.js with, for each printer: bed size, printable
height, excluded bed area, machine limits, and the official start, end,
layer-change and filament-change G-code templates.

Usage:
    git clone --depth 1 --filter=blob:none --sparse https://github.com/bambulab/BambuStudio.git
    git -C BambuStudio sparse-checkout set resources/profiles/BBL/machine
    python3 tools/import_bambu.py path/to/BambuStudio

To add a printer, add a line to PRINTERS below and run the script again.
"""
import json, os, sys, datetime

# id -> (display name, profile name in BambuStudio)
PRINTERS = [
    ("a1mini", "A1 mini", "Bambu Lab A1 mini 0.4 nozzle"),
    ("a1", "A1", "Bambu Lab A1 0.4 nozzle"),
    ("p1p", "P1P", "Bambu Lab P1P 0.4 nozzle"),
    ("p1s", "P1S", "Bambu Lab P1S 0.4 nozzle"),
    ("x1c", "X1 Carbon", "Bambu Lab X1 Carbon 0.4 nozzle"),
    ("h2d", "H2D", "Bambu Lab H2D 0.4 nozzle"),
]
TEMPLATES = ["machine_start_gcode", "machine_end_gcode", "layer_change_gcode", "change_filament_gcode"]


def main(root):
    mdir = os.path.join(root, "resources", "profiles", "BBL", "machine")
    files = {}
    for f in os.listdir(mdir):
        if f.endswith(".json"):
            with open(os.path.join(mdir, f), encoding="utf-8") as fh:
                d = json.load(fh)
            files[d.get("name", f[:-5])] = d

    def resolve(name):
        d = files[name]
        out = resolve(d["inherits"]) if d.get("inherits") in files else {}
        for inc in d.get("include", []) or []:
            if inc in files:
                out.update({k: v for k, v in files[inc].items() if k in TEMPLATES})
        out.update(d)
        return out

    def first(v, default=None):
        if isinstance(v, list):
            return v[0] if v else default
        return v if v is not None else default

    def area(pts):
        xy = [tuple(float(c) for c in p.split("x")) for p in pts]
        xs, ys = [p[0] for p in xy], [p[1] for p in xy]
        return min(xs), min(ys), max(xs), max(ys)

    out = []
    for pid, label, name in PRINTERS:
        r = resolve(name)
        x0, y0, x1, y1 = area(r["printable_area"])
        excl = r.get("bed_exclude_area") or []
        out.append({
            "id": pid,
            "name": label,
            "source": name,
            "bed": [x1 - x0, y1 - y0],
            "bedOrigin": [x0, y0],
            "maxHeight": float(first(r.get("printable_height"), 250)),
            "excludeArea": list(area(excl)) if len(excl) >= 3 else None,
            "nozzles": [0.2, 0.4, 0.6, 0.8],
            "maxSpeedXY": float(first(r.get("machine_max_speed_x"), 500)),
            "maxSpeedZ": float(first(r.get("machine_max_speed_z"), 20)),
            "maxAccel": float(first(r.get("machine_max_acceleration_extruding"), 10000)),
            "pauseGcode": r.get("machine_pause_gcode", "M400 U1"),
            "multiNozzle": len(r.get("nozzle_diameter", [])) > 1,
            "startGcode": r.get("machine_start_gcode", ""),
            "endGcode": r.get("machine_end_gcode", ""),
            "layerChangeGcode": r.get("layer_change_gcode", ""),
            "changeFilamentGcode": r.get("change_filament_gcode", ""),
        })

    dest = os.path.join(os.path.dirname(__file__), "..", "profiles", "printers.js")
    stamp = datetime.date.today().isoformat()
    with open(dest, "w", encoding="utf-8") as fh:
        fh.write("// Generated by tools/import_bambu.py from BambuStudio resources/profiles/BBL/machine (%s).\n" % stamp)
        fh.write("// Do not edit by hand: re-run the importer instead.\n")
        fh.write("(globalThis.DH = globalThis.DH || {}).PRINTERS = ")
        json.dump(out, fh, indent=1)
        fh.write(";\n")
    print("wrote", os.path.normpath(dest), "with", len(out), "printers")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
